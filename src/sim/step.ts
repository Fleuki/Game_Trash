import type { WorldState } from './types';

/**
 * Один шаг симуляции.
 *
 * Детерминирован: не читает часы, не трогает DOM, не использует Math.random.
 * Один и тот же мир и одна и та же последовательность шагов дают один и тот же результат.
 *
 * Аргумента с командами пока нет: вводить нечего до S2, а пустая шина была бы заглушкой.
 */
export function step(world: WorldState): void {
  world.tick++;
}
