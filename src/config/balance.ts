/**
 * Параметры цикла симуляции.
 *
 * Единственные числа среза S0. В коде систем чисел нет — правило 5 из PLAN §3.3.
 */

/** Шагов симуляции в секунду. Ускорение времени — это N шагов за кадр, а не другой шаг. */
export const TICK_RATE = 60;

/** Длительность одного шага в секундах. */
export const STEP = 1 / TICK_RATE;

/**
 * Потолок дельты кадра в секундах.
 *
 * Защита от фризов вкладки: больше этого за один кадр не догоняем, остаток отбрасываем.
 * Иначе возврат из фона даст пачку из тысяч шагов и фриз на несколько секунд.
 */
export const MAX_FRAME_DELTA = 0.25;

/**
 * Скорость ленты в клетках в секунду. Настраивается ползунком: пределы здесь,
 * текущее значение — в мире, потому что его меняет игрок.
 */
export const BELT_SPEED_DEFAULT = 2;
export const BELT_SPEED_MIN = 0.5;
export const BELT_SPEED_MAX = 8;

/**
 * Сколько тиков между выпусками предметов из источника.
 *
 * На свободной ленте выпущенные с интервалом предметы не догоняют друг друга:
 * при 2 кл/с расстояние между ними 0.67 клетки, а зазор нужен 0.4. Очередь
 * возникает только там, где линия встала. Число временное: настоящее придёт
 * из таблицы экономики вместе с объёмами районов.
 */
export const SPAWN_INTERVAL_TICKS = 20;

/**
 * Минимальный зазор между предметами в клетках. Предмет не подъедет к
 * впередиидущему ближе этого — отсюда берутся очередь и обратное давление.
 */
export const ITEM_GAP = 0.4;

/**
 * Длина дневной фазы в тиках. 3.5 минуты — середина вилки «3–4 минуты» из GDD §4.
 * Утро и вечер длятся столько, сколько нужно игроку: они на паузе.
 */
export const DAY_LENGTH_TICKS = 3.5 * 60 * TICK_RATE;

/** Доступные ускорения времени. Ноль — пауза. */
export const TIME_SPEEDS: readonly number[] = [0, 1, 2, 4];
