import type { MaterialId } from './materials';

/**
 * Вес примеси при расчёте чистоты партии.
 *
 * Органика считается вдвое — GDD §6. Это то, что делает её «ключевым материалом»:
 * из-за неё появляется смысл в очистке, а у остальных фракций — риск.
 */
export const IMPURITY_WEIGHT: Record<MaterialId, number> = {
  pet: 1,
  aluminium: 1,
  glass: 1,
  organic: 2,
};

/**
 * Пары материалов, которые сортировщик путает между собой.
 *
 * Стекло и прозрачный ПЭТ выглядят одинаково — GDD §5. Путаница считается,
 * только когда напарник по паре стоит по другую сторону правила: отделять
 * стекло от органики легко, стекло от ПЭТ — нет.
 */
export const CONFUSABLE: readonly (readonly [MaterialId, MaterialId])[] = [['glass', 'pet']];

/** Скорость ленты, при которой машины работают в паспортной точности. */
export const NOMINAL_BELT_SPEED = 2;

/**
 * Насколько падает точность за каждую «лишнюю» номинальную скорость.
 * Разогнал ленту вдвое — потерял столько точности. GDD §6: скорость против точности.
 */
export const SPEED_ACCURACY_PENALTY = 0.05;

/** Хуже этого машина не ошибается: иначе она превращается в подбрасывание монеты. */
export const MAX_ERROR_CHANCE = 0.6;

/** До этой скорости стекло едет целым. */
export const GLASS_SAFE_SPEED = 3;

/**
 * Шанс на тик разбить единицу стекла за каждую единицу скорости сверх безопасной.
 *
 * Подобрано так, чтобы бой был выбором, а не мелочью: на десятиклеточном пути
 * при 4 кл/с бьётся примерно пятая часть стекла, при 8 кл/с — около сорока
 * процентов. Число временное, окончательное придёт из таблицы экономики.
 */
export const GLASS_BREAK_PER_SPEED = 0.0015;

/** Вес боя при расчёте чистоты: осколки хуже обычной примеси, но лучше органики. */
export const BROKEN_GLASS_WEIGHT = 1.5;
