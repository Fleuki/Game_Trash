/**
 * Пока район один, он всегда этот.
 *
 * Иначе урок четвёртого дня — случайность: со «Стройки» органики не приедет
 * вовсе, а со свалки может приехать восемь десятых партии, и первое знакомство
 * с загрязнением обернётся днём в убыток. «Спальный район» даёт ровно то, что
 * обещает его описание: две трети ПЭТ, треть органики.
 */
export const TUTORIAL_DISTRICT = 'residential';

/**
 * Сколько партий показывать на рынке. Пока район один, выбирать не из чего —
 * и это правильно: в первые дни решение всего одно, довезти или не довезти.
 */
export function marketOfferLimit(day: number): number | null {
  if (day < 6) return 1;
  if (day < 10) return 2;
  return null;
}

/** Сколько заказов на доске и сколько можно держать разом. GDD §13: «один контракт». */
export function contractLimit(day: number): number | null {
  if (day < 6) return 1;
  return null;
}

